create table if not exists member (
    id integer generated by default as identity primary key,
    username varchar(100) unique,
    password varchar(255)
);
create table if not exists organizer (
    id integer primary key references member(id),
    full_name varchar(255), address varchar(255), date_of_birth timestamp, email varchar(255)
);
create table if not exists sponsor (
    id integer primary key references member(id), name varchar(255), tax_code varchar(14) not null unique,
    field varchar(255), address varchar(255), email varchar(255), tel varchar(255),
    status varchar(255) not null
);
create table if not exists contract (
    id integer generated by default as identity primary key, barcode varchar(255),
    sponsor_id integer not null references sponsor(id), organizer_id integer references organizer(id),
    signed_date date, effective_from date, effective_to date, status varchar(255)
);
